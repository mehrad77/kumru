// The Kumru page build, as a Vite plugin (docs/SPECS.md section 5.2, docs/SPECS_SCHEMA.md section 4.2).
// Vite bundles app/main.ts (the host, the bridge, the lazy chunks). This plugin adds what Vite does not know:
//
//   index.html          the shell (index.html) gets the favicon and head tags
//   data/<c>.<hash>.json, data/manifest.json   the content collections (data/), hashed
//   sw.js               app/host/sw.ts (a second Vite entry, built to /sw.js) with this build's version and precache list
//   brand files, _headers
//
// Modes: `production` (default), `drafts` (path sections marked "draft" too), `dev` (drafts, unminified, and the
// dev learner for the ?learner switch). `vite` (the dev server, `pnpm dev`) is always dev: it serves the data and
// brand files from memory and reloads the page when data/ or brand/ change. The build is deterministic: the same sources give the same bytes, and
// `version` (12 hex characters of a SHA-256 over every output) is also written to <meta name="kumru-version">.
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { transformWithOxc, type Plugin } from "vite";

const MIME: Record<string, string> = { ".json": "application/json", ".js": "text/javascript", ".svg": "image/svg+xml", ".png": "image/png", ".webp": "image/webp", ".webmanifest": "application/manifest+json" };

// cards, grammar and path load at boot; stories, characters and places (checked by sahne/packages/sahne-story/stories.ts --check) load
// when the Stories tab opens. Production leaves out draft path sections and draft stories.
const COLLECTIONS = ["cards", "grammar", "path", "stories", "characters", "places"] as const;
// Sahne's recordings (sahne/packages/sahne-kit/sounds), served under /sounds/<hash8>/ so they can be cached for ever; the stage's
// `sounds` base is in the manifest. They are fetched on first use, not precached.
const SOUNDS_DIR = ["sahne", "packages", "sahne-kit", "sounds"];
// The stories' thumbnails (data/thumbs, written by sahne/packages/sahne-gallery/thumbs.mjs), served the same way under /thumbs/<hash8>/
// (the manifest's `thumbs` base); the service worker caches each on first use.
const THUMBS_DIR = ["data", "thumbs"];

// The size gate (sahne/packages/sahne/DESIGN.md §12, ROADMAP.md M8): gzip KB of what each part of the page loads, checked on every build.
// `entry` is what the first paint needs (no Sahne code may be in it); the lazy libraries are counted with all they pull in that
// the entry does not already carry; a set family is one chunk.
const BUDGET_KB = { entry: 85, avatar: 150, builder: 240, player: 265, family: 40 } as const;
// the lazy libraries whose code the service worker fetches on first use instead of precaching
const LAZY_LIBS = ["app/lib/builder.ts", "app/lib/player.ts"];
const BRAND_FILES = ["manifest.webmanifest", "icon.svg", "icon-192.png", "icon-512.png", "apple-touch-icon-180.png"];
const HEADERS = `# generated by scripts/vite/page.ts; do not edit
/data/*
  Cache-Control: public, max-age=31536000, immutable
/data/manifest.json
  ! Cache-Control
  Cache-Control: no-cache
/assets/*
  Cache-Control: public, max-age=31536000, immutable
/sounds/*
  Cache-Control: public, max-age=31536000, immutable
/thumbs/*
  Cache-Control: public, max-age=31536000, immutable
/sw.js
  Cache-Control: no-cache
/*.png
  Cache-Control: public, max-age=86400
/icon.svg
  Cache-Control: public, max-age=86400
/manifest.webmanifest
  Cache-Control: public, max-age=86400
`;

type Doc = Record<string, unknown>;
type Out = string | Buffer;

const sha = (data: Out) => createHash("sha256").update(data).digest("hex");

const sortKeys = (v: unknown): unknown => {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v && typeof v === "object") {
    return Object.fromEntries(Object.entries(v as Doc).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([k, x]) => [k, sortKeys(x)]));
  }
  return v;
};

/** JSON as the build has always written it: keys sorted at every level, no spaces. */
const compact = (value: unknown) => JSON.stringify(sortKeys(value));

export function kumruPage(opts: { mode: string; serve: boolean }): Plugin {
  const dev = opts.serve || opts.mode === "dev";
  const drafts = dev || opts.mode === "drafts";
  let root = "";
  let outDir = "";
  let isBuild = false;
  let written: string[] = [];
  let plan: ReturnType<typeof chunkPlan> | null = null;

  const src = (...p: string[]) => path.join(root, ...p);

  function loadDir(sub: string, pattern = /\.json$/): Record<string, Doc> {
    const dir = src("data", sub);
    const out: Record<string, Doc> = {};
    for (const f of readdirSync(dir).filter((n) => pattern.test(n)).sort()) {
      out[f.replace(/\.json$/, "")] = JSON.parse(readFileSync(path.join(dir, f), "utf8"));
    }
    return out;
  }

  function collection(name: string): Record<string, Doc> {
    let docs: Record<string, Doc>;
    if (name === "cards") {
      docs = loadDir("cards");
      const extra = loadDir("cards-extra");
      const both = Object.keys(extra).filter((k) => k in docs);
      if (both.length) throw new Error(`cards in both data/cards and data/cards-extra: ${both.slice(0, 5)}`);
      Object.assign(docs, extra);
    } else if (name === "path") {
      docs = Object.fromEntries(Object.entries(loadDir("path", /^s[0-9][0-9]\.json$/)).filter(([, v]) => drafts || !v.draft));
    } else if (name === "stories") {
      docs = Object.fromEntries(Object.entries(loadDir("stories")).filter(([, v]) => drafts || !v.draft));
    } else {
      docs = loadDir(name);
    }
    return Object.fromEntries(Object.keys(docs).sort().map((k) => [k, { ...docs[k], id: k }]));
  }

  /** A public var from wrangler.jsonc (JSONC: line comments allowed). */
  function wranglerVar(name: string): string {
    const text = readFileSync(src("wrangler.jsonc"), "utf8").replace(/^\s*\/\/.*$/gm, "");
    return String((JSON.parse(text).vars ?? {})[name] ?? "");
  }

  let headTags: { icon: string; light: string; dark: string } | null = null;
  /** Kerim's head as the favicon and the theme colours, from scripts/kumru_icons.py (the one reader of K_HEAD). */
  function icons() {
    headTags ??= JSON.parse(execFileSync("uv", ["run", "scripts/kumru_icons.py", "--head-tags"], { cwd: root, encoding: "utf8" }));
    return headTags!;
  }

  /** A learner part-way through A1 who has just started A2, with old-style prefs so the migration runs. */
  function devLearner(cards: Record<string, Doc>, grammar: Record<string, Doc>) {
    let seed = 1;
    const rnd = () => {   // mulberry32: a small seeded generator, so the dev learner is the same every build
      seed = (seed + 0x6d2b79f5) | 0;
      let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
    const share: Record<string, number> = { A1_1: 0.95, A1_2: 0.9, A1_3: 0.85, A1_4: 0.6, A1_5: 0.3, A2_1: 0.15 };
    const box: Record<string, number> = {};
    const stats: Record<string, unknown> = {};
    for (const [cid, c] of Object.entries(cards)) {
      const p = share[String(c.ref ?? "")] ?? 0;
      const known = rnd() < p;
      if (known) {
        box[cid] = [3, 4, 5][Math.floor(rnd() * 3)];
        stats[cid] = { g: 3, e: 1 };
      } else if (rnd() < p) {
        box[cid] = 1;
        stats[cid] = { a: 1 };
      }
    }
    const gram = Object.fromEntries(Object.entries(grammar).filter(([, v]) => ["A1_1", "A1_2", "A1_3"].includes(String(v.ref))).map(([g]) => [g, 1]));
    return { box, stats, gram, drill: {}, days: {}, ex: {}, log: [], nick: "Test", st: {}, prefs: { level: "A1", startUnit: 1, talkPlan: false }, onb: 4 };
  }

  /** The hashed collection files, the recordings, the thumbnails, and what the manifest says about them. */
  function dataFiles() {
    const extra: Record<string, Out> = {};
    const filesMap: Record<string, string> = {};
    const counts: Record<string, number> = {};
    for (const name of COLLECTIONS) {
      const docs = collection(name);
      const text = compact(docs) + "\n";
      const rel = `data/${name}.${sha(text).slice(0, 8)}.json`;
      extra[rel] = text;
      filesMap[name] = rel;
      counts[name] = Object.keys(docs).length;
    }
    const dir = src(...SOUNDS_DIR), rec = readdirSync(dir).filter((f) => f.endsWith(".m4a")).sort();
    const h = createHash("sha256");
    for (const f of rec) h.update(f + "\0").update(readFileSync(path.join(dir, f)));
    const sounds = `sounds/${h.digest("hex").slice(0, 8)}/`;
    for (const f of rec) extra[sounds + f] = readFileSync(path.join(dir, f));
    const tdir = src(...THUMBS_DIR), pics = existsSync(tdir) ? readdirSync(tdir).filter((f) => f.endsWith(".webp")).sort() : [];
    const th = createHash("sha256");
    for (const f of pics) th.update(f + "\0").update(readFileSync(path.join(tdir, f)));
    const thumbs = `thumbs/${th.digest("hex").slice(0, 8)}/`;
    for (const f of pics) extra[thumbs + f] = readFileSync(path.join(tdir, f));
    return { extra, filesMap, counts, sounds: "/" + sounds, thumbs: "/" + thumbs };
  }

  /**
   * The page's chunks split by how they are loaded: `eager` reaches the entry through static and dynamic imports without
   * passing a lazy library (the service worker precaches it); `lazy` is the rest (fetched and cached on first use). Also the
   * size gate: each part's gzip KB against BUDGET_KB; a build over budget fails.
   */
  function chunkPlan(bundle: Record<string, { type: string; fileName: string; code?: string; imports?: string[]; dynamicImports?: string[]; facadeModuleId?: string | null; moduleIds?: string[]; isEntry?: boolean; name?: string }>) {
    const chunks = Object.values(bundle).filter((c) => c.type === "chunk" && c.fileName !== "sw.js");
    const by = new Map(chunks.map((c) => [c.fileName, c]));
    const rel = (id?: string | null) => (id ? path.relative(root, id).split(path.sep).join("/") : "");
    const lazyRoot = (c: (typeof chunks)[number]) => LAZY_LIBS.includes(rel(c.facadeModuleId));
    const walk = (from: string[], dynamic: boolean, stop: (c: (typeof chunks)[number]) => boolean) => {
      const seen = new Set<string>(), todo = [...from];
      while (todo.length) {
        const f = todo.pop()!, c = by.get(f);
        if (!c || seen.has(f) || stop(c)) continue;
        seen.add(f);
        todo.push(...(c.imports ?? []), ...(dynamic ? c.dynamicImports ?? [] : []));
      }
      return seen;
    };
    const entry = chunks.filter((c) => c.isEntry).map((c) => c.fileName);
    const eager = walk(entry, true, lazyRoot);
    const lazy = chunks.map((c) => c.fileName).filter((f) => !eager.has(f));
    // the gate
    const kb = (files: Iterable<string>) => [...files].reduce((n, f) => n + gzipSync(by.get(f)!.code ?? "", { level: 9 }).length, 0) / 1024;
    const initial = walk(entry, false, () => false);
    const closure = (lib: string, minus: Set<string>) => {
      const c = chunks.find((x) => rel(x.facadeModuleId) === lib);
      return c ? new Set([...walk([c.fileName], false, () => false)].filter((f) => !minus.has(f))) : null;
    };
    const rows: [string, number, number][] = [["entry", kb(initial), BUDGET_KB.entry]];
    for (const [name, lib] of [["avatar", "app/lib/avatar.ts"], ["builder", "app/lib/builder.ts"], ["player", "app/lib/player.ts"]] as const) {
      const set = closure(lib, initial);
      if (set) rows.push([name, kb(set), BUDGET_KB[name]]);
    }
    const sahneInEntry = [...initial].flatMap((f) => by.get(f)!.moduleIds ?? []).map(rel)
      .filter((m) => /^\.\.\/\.\.\/packages\/sahne(-kit|-tr|-story)?\/src\//.test(m) && !m.endsWith("sahne-kit/src/kerim/art.ts"));
    for (const c of chunks) {
      const fam = (c.moduleIds ?? []).map(rel).find((m) => /packages\/sahne-kit\/src\/set\/[a-z]+\.ts$/.test(m) && !/\/(index|families\.gen)\.ts$/.test(m));
      if (fam && rel(c.facadeModuleId) === fam) rows.push(["set " + path.basename(fam, ".ts"), kb([c.fileName]), BUDGET_KB.family]);
    }
    const over = rows.filter(([, n, max]) => n > max);
    // KUMRU_SIZE=entry lists the entry's biggest modules (rendered length), to find what grew it
    if (process.env.KUMRU_SIZE === "chunks") console.log([...initial].map((f) => `${kb([f]).toFixed(1)}\t${f}\t${(by.get(f)!.moduleIds ?? []).length}`).join("\n"));
    if (process.env.KUMRU_SIZE === "entry") {
      const mods = [...initial].flatMap((f) => Object.entries((by.get(f) as unknown as { modules?: Record<string, { renderedLength: number }> }).modules ?? {}));
      console.log(mods.sort((a, b) => b[1].renderedLength - a[1].renderedLength).slice(0, 400).map(([m, x]) => `${x.renderedLength}\t${rel(m)}`).join("\n"));
    }
    return { lazy, rows, over, sahneInEntry };
  }

  /** The service worker with its build placeholder (a string literal, `JSON.parse("__BUILD__")`) filled in. */
  function withBuild(code: string, build: { version: string; files: string[]; lazy: string[] }): string {
    const re = /(["'`])__BUILD__\1/g;
    if ((code.match(re) ?? []).length !== 1) throw new Error('app/host/sw.ts must contain the "__BUILD__" placeholder exactly once');
    return code.replace(re, () => JSON.stringify(compact(build)));
  }

  const headExtra = () => '<link rel="manifest" href="/manifest.webmanifest">'
    + '<link rel="apple-touch-icon" href="/apple-touch-icon-180.png">'
    + '<meta name="kumru-version" content="@version">'
    + `<meta name="kumru-turnstile" content="${dev ? "" : wranglerVar("TURNSTILE_SITE_KEY")}">`;

  function devBlob(colls: Record<string, Record<string, Doc>>): string {
    const tree = Object.entries(colls.path).sort(([, a], [, b]) => Number(a.order) - Number(b.order))
      .map(([sid, sec]) => [sid, (sec.skills as { id: string }[]).map((sk) => sk.id)]);
    return `<script>window.__KUMRU_DEV__=${compact({ learner: devLearner(colls.cards, colls.grammar), tree })};</script>`;
  }

  return {
    name: "kumru-page",
    enforce: "post",
    configResolved(config) {
      root = config.root;
      outDir = path.resolve(config.root, config.build.outDir);
      isBuild = config.command === "build";
    },
    configureServer(server) {
      // the dev server answers what the build would write: the hashed data files, the manifest, the brand files
      let cache: { files: Map<string, Out> } | null = null;
      const served = () => {
        if (!cache) {
          const { extra, filesMap, counts, sounds, thumbs } = dataFiles();
          const files = new Map<string, Out>(Object.entries(extra).map(([rel, v]) => ["/" + rel, v]));
          files.set("/data/manifest.json", JSON.stringify(sortKeys({ counts, files: filesMap, sounds, thumbs, v: 1, version: "dev" }), null, 1) + "\n");
          for (const f of BRAND_FILES) if (existsSync(src("brand", f))) files.set("/" + f, readFileSync(src("brand", f)));
          cache = { files };
        }
        return cache.files;
      };
      const watched = ["data", "brand", path.join("app", "host", "sw.ts")].map((d) => src(d));
      server.watcher.add(watched);
      const changed = (file: string) => {
        if (!watched.some((w) => file === w || file.startsWith(w + path.sep))) return;
        cache = null;
        server.ws.send({ type: "full-reload" });
      };
      for (const ev of ["add", "change", "unlink"] as const) server.watcher.on(ev, changed);
      server.middlewares.use(async (req, res, next) => {
        const url = (req.url ?? "").split("?")[0];
        const send = (body: Out, type: string) => {
          res.setHeader("Content-Type", type);
          res.setHeader("Cache-Control", "no-cache");
          res.end(body);
        };
        if (url === "/sw.js") {   // the worker is not part of the module graph in dev: compile it on request
          const { code } = await transformWithOxc(readFileSync(src("app", "host", "sw.ts"), "utf8"), "sw.ts");
          return send(withBuild(code, { version: "dev", files: ["/"], lazy: [] }), MIME[".js"]);
        }
        let body: Out | undefined;
        try { body = served().get(url); } catch (e) { return next(e as Error); }
        if (body === undefined) return next();
        send(body, MIME[path.extname(url)] ?? "application/octet-stream");
      });
    },
    transformIndexHtml: {
      order: "post",
      handler(html) {
        for (const marker of ["<!-- @icon -->"]) {
          if (html.split(marker).length !== 2) throw new Error(`index.html must contain ${marker} exactly once`);
        }
        if (html.split("</head>").length !== 2) throw new Error("index.html must contain </head> exactly once");
        const i = icons();
        const iconTags = `<link rel="icon" type="image/svg+xml" href="${i.icon}">`
          + `<meta name="theme-color" content="${i.light}" media="(prefers-color-scheme: light)">`
          + `<meta name="theme-color" content="${i.dark}" media="(prefers-color-scheme: dark)">`;
        const blob = dev ? devBlob(Object.fromEntries(COLLECTIONS.map((c) => [c, collection(c)]))) : "";
        // a function, not a string: `$` in the sources must not be read as a replacement pattern
        return html
          .replace("</head>", () => blob + (opts.serve ? headExtra().replace('content="@version"', 'content="dev"') : headExtra()) + "</head>")
          .replace("<!-- @icon -->", () => iconTags);
      },
    },
    // The entry stylesheet is inlined into the page, so the first paint (the sign-in gate) needs no CSS request. Stylesheets of
    // lazy chunks stay files: they arrive with their chunk and are precached by the service worker.
    generateBundle: {
      order: "post",
      handler(_options, bundle) {
        const page = bundle["index.html"];
        if (!isBuild || !page || page.type !== "asset") return;
        let html = String(page.source);
        for (const m of [...html.matchAll(/<link rel="stylesheet"[^>]*href="\/([^"]+\.css)"[^>]*>/g)]) {
          const css = bundle[m[1]];
          if (!css || css.type !== "asset") continue;
          html = html.replace(m[0], () => "<style>" + String(css.source).trimEnd() + "</style>");
          delete bundle[m[1]];
        }
        page.source = html;
      },
    },
    writeBundle(_options, bundle) {
      written = Object.keys(bundle);
      plan = chunkPlan(bundle as unknown as Parameters<typeof chunkPlan>[0]);
    },
    closeBundle() {
      if (!isBuild || !written.length) return;
      const { extra, filesMap, counts, sounds, thumbs } = dataFiles();
      for (const f of BRAND_FILES) if (existsSync(src("brand", f))) extra[f] = readFileSync(src("brand", f));
      extra._headers = HEADERS;

      const swBundle = readFileSync(path.join(outDir, "sw.js"), "utf8");
      const page = readFileSync(path.join(outDir, "index.html"), "utf8");
      const bundleFiles = written.filter((f) => f !== "index.html" && f !== "sw.js").sort();
      // the version hashes everything the build writes, so any change to page, data, bundle or brand gives a new one
      const h = createHash("sha256");
      const all: Record<string, Out> = { ...extra };
      for (const f of bundleFiles) all[f] = readFileSync(path.join(outDir, f));
      for (const k of Object.keys(all).sort()) h.update(k + "\0").update(all[k]);
      h.update(page).update(swBundle);
      const version = h.digest("hex").slice(0, 12);

      const outputs: Record<string, Out> = { ...extra };
      outputs["index.html"] = page.replace('content="@version"', `content="${version}"`);
      outputs["data/manifest.json"] = JSON.stringify(sortKeys({ counts, files: filesMap, sounds, thumbs, v: 1, version }), null, 1) + "\n";
      const lazy = new Set(plan?.lazy ?? []);
      const precache = ["/", "/data/manifest.json", ...COLLECTIONS.map((c) => "/" + filesMap[c]),
        ...BRAND_FILES.filter((f) => f in outputs).map((f) => "/" + f), ...bundleFiles.filter((f) => !lazy.has(f)).map((f) => "/" + f)];
      outputs["sw.js"] = withBuild(swBundle, { version, files: precache, lazy: [...lazy].sort().map((f) => "/" + f) });
      if (plan && !dev) {   // a dev build is not minified: its sizes say nothing
        this.info?.("size (KB gzip): " + plan.rows.map(([n, kb, max]) => `${n} ${kb.toFixed(1)}/${max}`).join(", "));
        if (plan.sahneInEntry.length) throw new Error("Sahne code reached the entry chunk (keep it behind host.lib): " + plan.sahneInEntry.slice(0, 5).join(", "));
        if (plan.over.length) throw new Error("over the size budget (scripts/vite/page.ts BUDGET_KB): " + plan.over.map(([n, kb, max]) => `${n} ${kb.toFixed(1)} KB > ${max}`).join("; "));
      }

      // write in place and only then drop stale files, so a running `wrangler dev` never sees an empty folder
      for (const [rel, v] of Object.entries(outputs)) {
        const p = path.join(outDir, rel);
        mkdirSync(path.dirname(p), { recursive: true });
        const data = typeof v === "string" ? Buffer.from(v, "utf8") : v;
        if (!existsSync(p) || Buffer.compare(readFileSync(p), data) !== 0) writeFileSync(p, data);
      }
      const keep = new Set([...Object.keys(outputs), ...bundleFiles]);
      const sweep = (dir: string) => {
        for (const name of readdirSync(dir)) {
          const p = path.join(dir, name);
          if (statSync(p).isDirectory()) {
            sweep(p);
            if (!readdirSync(p).length) rmSync(p, { recursive: true });
          } else if (!keep.has(path.relative(outDir, p).split(path.sep).join("/"))) {
            rmSync(p);
          }
        }
      };
      sweep(outDir);
      const size = Object.values({ ...all, ...outputs }).reduce((n: number, v) => n + v.length, 0);
      this.info?.(`version ${version} (${(size / 1e6).toFixed(1)} MB): ` + COLLECTIONS.map((c) => `${c} ${counts[c]}`).join(", "));
    },
  };
}
