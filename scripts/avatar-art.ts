// Writes app/ui/avatar/silhouette.gen.ts, Sahne's paper silhouette (sahne/packages/sahne/DESIGN.md §10), and
// app/features/onboarding/cast.gen.ts, the head portraits of the Season 1 cast that onboarding's last step shows: drawn from
// the kit at build time so the page can show them without loading the kit (about 130 KB gzip).
// node scripts/avatar-art.ts [--check]   (--check fails when a file is stale; run by app/ui/avatar/silhouette.test.ts)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { portrait, silhouette } from "../sahne/packages/sahne/src/render/still/portrait.ts";
import { kit } from "../sahne/packages/sahne-kit/src/index.ts";

/** Kumru's cast roster (data/characters/, the folder Sahne reads as SAHNE_CONTENT/characters). */
const CHARACTERS = new URL("../data/characters/", import.meta.url);

/** How many of the cast onboarding shows: cast.gen.ts stays under about 40 KB (a head is 6 to 10 KB at any detail). */
export const CAST_SHOWN = 5;

interface CastDoc { id: string; kind?: string; name: string; nameFa?: string; order?: number; avatar?: unknown }

/** The cast onboarding's last step shows, in this order. */
export const ONBOARDING_CAST = ["ismail", "berfin", "elif", "serkan", "omer"];

/** The cast onboarding shows: the characters of ONBOARDING_CAST, each a roster character (`kind: "cast"`) with an avatar. */
export function castShown(): CastDoc[] {
  return readdirSync(CHARACTERS).filter((f) => f.endsWith(".json"))
    .map((f) => JSON.parse(readFileSync(new URL(f, CHARACTERS), "utf8")) as CastDoc)
    .filter((c) => c.kind === "cast" && c.avatar && ONBOARDING_CAST.includes(c.id))
    .sort((a, b) => ONBOARDING_CAST.indexOf(a.id) - ONBOARDING_CAST.indexOf(b.id))
    .slice(0, CAST_SHOWN);
}

/** silhouette.gen.ts: in the entry chunk (portrait.ts imports it), so it holds the silhouette alone. */
export function avatarArtText(): string {
  const head = silhouette(kit, { framing: "head", detail: 96, idPrefix: "sil" });
  return [
    "// Generated by scripts/avatar-art.ts from the Sahne kit; do not edit.",
    "/** Sahne's silhouette at head framing, an SVG that scales to its box: lists show it before a learner has a character. */",
    `export const SILHOUETTE_HEAD = ${JSON.stringify(head)};`,
    "",
  ].join("\n");
}

/** cast.gen.ts: imported only by onboarding's last step (steps/Rest.tsx), in the lazy onboarding chunk. */
export function castHeadsText(): string {
  const cast = castShown().map((c) => ({
    id: c.id, name: c.name, nameFa: c.nameFa ?? "",
    // the span around it carries the name (role img); the picture itself is hidden from screen readers
    svg: portrait(c.avatar, kit, { framing: "head", trusted: true, detail: 46, idPrefix: "c" + c.id }).replace(/^<svg\b/, '<svg aria-hidden="true"'),
  }));
  return [
    "// Generated by scripts/avatar-art.ts from the Sahne kit and data/characters; do not edit.",
    "/** The Season 1 cast onboarding shows (castShown in scripts/avatar-art.ts): head portraits, SVGs that scale to their box. */",
    `export const CAST_HEADS: readonly { id: string; name: string; nameFa: string; svg: string }[] = ${JSON.stringify(cast, null, 1)};`,
    "",
  ].join("\n");
}

/** Every file this script writes, by its path from . */
export const FILES: { path: string; text: () => string }[] = [
  { path: "app/ui/avatar/silhouette.gen.ts", text: avatarArtText },
  { path: "app/features/onboarding/cast.gen.ts", text: castHeadsText },
];
const url = (path: string): URL => new URL("../" + path, import.meta.url);
const stale = (f: (typeof FILES)[number]): boolean => { try { return readFileSync(url(f.path), "utf8") !== f.text(); } catch { return true; } };

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes("--check")) {
    const bad = FILES.filter(stale);
    for (const f of bad) console.error(`${f.path} is stale: run node scripts/avatar-art.ts`);
    if (bad.length) process.exit(1);
  } else {
    for (const f of FILES) { writeFileSync(url(f.path), f.text()); console.log("wrote " + f.path); }
  }
}
