// Writes shared/cast-parts.gen.ts: the kit's part ids reserved for the cast (sahne/packages/sahne-kit/src/curation.ts,
// `avail: "cast"`), which a learner's `char` may not wear (shared/char.ts charProblem, the Worker's check).
// node scripts/cast-parts.ts [--check]   (--check fails when the file is stale; run by shared/char.test.ts)
import { readFileSync, writeFileSync } from "node:fs";
import { PARTS } from "../sahne/packages/sahne-kit/src/curation.ts";

const OUT = new URL("../shared/cast-parts.gen.ts", import.meta.url);

export function castPartsText(): string {
  const ids = Object.entries(PARTS).filter(([, c]) => c.avail === "cast").map(([id]) => id).sort();
  return [
    "// Generated by scripts/cast-parts.ts from sahne/packages/sahne-kit/src/curation.ts; do not edit.",
    "/** The kit's part ids reserved for the cast: a learner's `char` may not wear them. */",
    `export const CAST_PARTS: readonly string[] = ${JSON.stringify(ids)};`,
    "",
  ].join("\n");
}

const stale = (): boolean => { try { return readFileSync(OUT, "utf8") !== castPartsText(); } catch { return true; } };

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes("--check")) {
    if (stale()) { console.error("shared/cast-parts.gen.ts is stale: run node scripts/cast-parts.ts"); process.exit(1); }
  } else {
    writeFileSync(OUT, castPartsText());
    console.log("wrote shared/cast-parts.gen.ts");
  }
}
